def cell(s):
    return str(s).replace('|', '｜').replace('\n', ' ')


def all_slides(meta):
    return [s for ph in meta['phases'] for s in ph['slides']]


def lesson_plan(meta, phases, spiral, grade):
    k = meta['type']
    slides = all_slides(meta)
    tasks = [s for s in slides if s['_k'] in ('tasks', 'drill')]
    mistakes = [s for s in slides if s['_k'] == 'mistake']
    ex = next(s for s in slides if s['_k'] == 'exit')['_d']
    hook = next((s['_d'] for s in slides if s['_k'] == 'hook'), None)
    L = [f"# L{meta['id']:02d}　{meta['code']} {meta['topic']}（{TYPE_LABEL[k]}）", '',
         f"> 課型：**{TYPE_LABEL[k]}**｜工作紙 {meta['code']} 網頁版（共 8 份）｜教材範圍：{meta['unit']}。"
         '題目取自同名工作紙（原設計 50 分鐘），這裏依練習課技能編成 40 分鐘：每層每關先做第 1 題，第 2 題放在第 4 階段。'
         '學生表現一律為「預期情況」，實際請依課堂證據調整。', '',
         '## A. 課堂基本資料', '',
         f'- 年級：{grade}', f"- 課題：{meta['topic']}", '- 課時：40分鐘', f"- 課型：{TYPE_LABEL[k]}",
         f"- 核心學習目標：{meta['goal']}", f"- 先備知識：{meta['prior']}", f"- 教學重點：{meta['focus']}",
         f"- 學習難點：{meta['difficulty']}", f"- 本節刻意不教：{meta.get('boundary', '無')}", '',
         '## B. 40分鐘教學流程表', '',
         '| 時間 | 階段 | 教師活動 | 學生活動 | 分層支持 | 學習證據 | 對應投影片 |', '|------|------|----------|----------|----------|----------|------------|']
    for i, ph in enumerate(phases):
        secs = '、'.join(f"{s['code']} {s['name']}" for s in ph['sections'] if s['kind'] != 'help')
        t = T[k][i]
        L.append(f"| {cell(ph['time'])} | {cell(ph['teacher_title'])} | {t[0]} | {t[1]} | {t[2]} | {t[3]} | {cell(secs)} |")
    L += ['']
    for i, ph in enumerate(phases):
        ss = meta['phases'][i]['slides']
        checks = [s['_d']['q'] for s in ss if s['_k'] == 'check']
        trouble = [o['why'] for s in ss if s['_k'] == 'check' for o in s['_d']['options'] if not o['ok']][:3]
        trouble += [s['_d']['why'] for s in ss if s['_k'] == 'mistake'][:2]
        t = T[k][i]
        L += [f"### 第 {i + 1} 階段　{ph['time']}　{ph['teacher_title']}（簡報：{ph['title']}；螺旋：{ph['spiral']}）", '',
              f'- 教師活動：{t[0]}', f'- 學生活動：{t[1]}',
              '- 教學資源：互動簡報 ' + '、'.join(f"{s['sec']} {s['secName']}" for s in ss if s['_k'] != 'help') + '；學習單（handout.html）。',
              '- 理解檢查：' + ('；'.join(checks) if checks else t[3]),
              '- 可能困難（預期情況）：' + ('；'.join(trouble) if trouble else '起步較慢、未能用手勢表態。'),
              f'- 應對策略：{STRAT}', f'- 支援提示：{SUP[k][i]}', '']
        if i == 1 and k == 'new' and hook:
            L.insert(-1, f"- 懸念：{hook['ask']}（當下不給答案，第 6 階段揭曉：{meta.get('reveal', '見 6-2')}）")
    L += ['## C. 課堂練習', '']
    for s in tasks:
        d = s['_d']
        L += [f"### {s['sec']} {s['secName']}" + (f"（專注 {d['timer']} 分鐘）" if d.get('timer') else ''), '',
              '| 層次 | 題目 | 答案 | 提示階梯 |', '|------|------|------|----------|']
        names = {'A': 'A層 基礎支持', 'B': 'B層 核心達標', 'C': 'C層 延伸挑戰'}
        for x in d['tiers']:
            L.append(f"| {names[x['tier']]} | {cell(x['q'])} | {cell(x['ans'])} | {cell('；'.join(x.get('hints') or []) or '不設提示，鼓勵先自行解釋')} |")
        L += ['']
    watch = [w for s in tasks for w in (s['_d'].get('watch') or [])]
    L += ['### 巡視觀察表（也印在 handout.html 的教師版）', '', '| 觀察重點（錯誤類型） | 人數 | 用於錯誤分析 |', '|------|------|------|']
    L += [f'| {cell(w)} |  | ☐ |' for w in watch] + ['| 其他： |  | ☐ |', '']
    L += ['### 不同學生的支援', '', '| 學生情況 | 本節做法 |', '|------|------|',
          f"| 基礎薄弱 | {meta.get('supportA', '從 A 層與提示階梯開始，先確認先備知識地圖中的舊知識；成功後逐步減少提示，不長期只做低層次題。')} |",
          '| 動機不足 | 任務短而明確、可自選層次、先猜後驗，讓學生看到可達成的進步；不等同懶惰。 |',
          '| 疲累或注意力不足 | 每段都有短回應（手勢、拖滑桿）；任務分段；個別關心，持續異常疲倦依校方程序跟進，不當成紀律問題。 |',
          '| 能力較高 | 做 C 層的解釋、比較、推理與遷移；不固定安排為其他學生的助手。 |', '']
    L += ['## D. 典型錯誤分析', '', '以下均為「預期錯誤」（未取自真實學生作答），教師可換成當堂收集、去識別化的例子。', '']
    follow = tasks[-1]['_d']['tiers'][1]['q'] if tasks else ''
    for s in mistakes:
        d = s['_d']
        steps = ' → '.join(d['steps'])
        L += [f"### {s['sec']} {s['title']}", '', f"- 題目：{d['q']}", f'- 錯誤示例：{steps}（錯在第 {d["wrong"] + 1} 步）',
              f"- 可能原因：{d['why']}", '- 診斷問題：這個解法哪一步開始出現問題？為甚麼這樣計算不正確？怎樣檢查答案是否合理？',
              '- 教師引導方式：不公開學生身份；先讓學生指出步驟，再追問成因，最後由學生修正。', f"- 正確做法：{d['fix']}",
              f'- 修正後練習：{follow}', '']
    r = ex['rubric']
    L += ['## E. 出口題及評估', '', f"- 出口題：{ex['q']}", f"- 參考答案：{ex['ans']}", '- 時間：2～3 分鐘，獨立完成。', '',
          '| 結果 | 判準及下一節安排 |', '|------|------|', f"| 已掌握 | {cell(r['mastered'])} |", f"| 部分掌握 | {cell(r['partial'])} |", f"| 尚未掌握 | {cell(r['notyet'])} |", '',
          '## F. 課後反思（上課後由教師依真實證據填寫）', '', '- 本節課最有效的設計：', '- 學生最常見的困難：', '- 需要個別跟進的學生：', '- 下一節課的調整：', '',
          '## G. 螺旋設計與學習追蹤', '', f'**本課型路徑**：{spiral}', '', '| 時間 | 階段 | 螺旋位置 |', '|------|------|------|']
    L += [f"| {cell(ph['time'])} | {cell(ph['teacher_title'])} | {cell(ph['spiral'])} |" for ph in phases]
    L += ['', '### 1. 先備知識地圖', '', '| 舊知識 | 本課怎樣用 | 怎樣確認（哪一頁或哪一題） | 不足時的補救 |', '|------|------|------|------|']
    L += ['| ' + ' | '.join(cell(c) for c in row) + ' |' for row in meta['priorMap']]
    d = meta['deep']
    L += ['', '### 2. 螺旋深化路徑', '', f"- 學生已經理解：{d[0]}", f"- 本次新增的理解：{d[1]}", f"- 之後會延伸到：{d[2]}", '',
          '### 3. 分層學習任務', '', '| 學生 | 任務層 | 支持方式 | 完成後 |', '|------|------|------|------|',
          '| 基礎薄弱 | A 層 | 提示階梯、附圖與第一步線索 | 嘗試 B 層 |', '| 一般 | B 層 | 必要時看提示 | 嘗試 C 層 |', '| 能力較高 | C 層 | 少提示，要求解釋或比較 | 自編變式題 |', '',
          '分層指任務與支持不同，不是固定學生標籤；學生可依表現隨時換層。', '',
          '### 4. 間隔重現計劃', '', '| 概念 | 何時再出現 | 形式（改變題目或情境） |', '|------|------|------|']
    L += ['| ' + ' | '.join(cell(c) for c in row) + ' |' for row in meta['spaced']]
    dl = ex['delayed']
    L += ['', '### 5. 學習證據追蹤', '', '- 出口題（當堂）：見 E 節。', f"- 延遲檢測（{dl['when']}，不提前通知、不先複習、不計分）：{dl['q']}　答案：{dl['ans']}", '',
          '| 出口題 | 延遲檢測 | 判斷 | 跟進 |', '|------|------|------|------|', '| 已掌握 | 已掌握 | 真正掌握 | 進入更高層次任務 |', '| 已掌握 | 未掌握 | 短暫學會 | 增加間隔重現，改變情境再練 |',
          '| 未掌握 | 已掌握 | 延後學會 | 了解後續哪些安排有效 |', '| 未掌握 | 未掌握 | 尚未掌握 | 找出成因，小組或個別重建概念 |', '',
          '## 教案品質檢查', '']
    Q = ['是否具有明確、可觀察的學習目標？', '各教學階段的總時間是否為40分鐘？', '是否讓不同程度學生都有明確任務？', '是否設計至少兩個理解檢查點？',
         '是否安排學生獨立思考及解題？', '是否預測典型數學錯誤？', '是否提供分層支持？', '是否包含有效的出口題？', '是否說明如何利用學習證據調整教學？',
         '是否考慮教師實際工作量及課堂可行性？', '簡報是否至少 25 頁（含階段頁），最後一頁是否為本節核心知識小結？', '是否標明各階段在螺旋路徑的位置？', '是否有先備知識地圖？',
         '是否說明本次比過去增加了哪些新理解？', '是否規劃間隔重現？', '是否設計延遲檢測，能分辨短暫學會與真正掌握？']
    L += [f'- [x] {q}' for q in Q] + ['']
    return '\n'.join(L)
